// cap09/cap10: desativar/reativar/excluir, Camila, menu da conta. Parte de t2/apos-cap08 (8 usuários).
const geom = (page, sel) => page.evaluate((s) => [...document.querySelectorAll(s)].map((e) => { const r = e.getBoundingClientRect(); return { t: (e.getAttribute('aria-label') || e.textContent || '').trim().replace(/\s+/g, ' ').slice(0, 40), x: Math.round(r.x), y: Math.round(r.y), w: Math.round(r.width), h: Math.round(r.height) }; }), sel);
const contador = (page) => page.evaluate(() => { const m = document.body.innerText.match(/\d+\/\d+ usuários • \d+ ativos?/); return m ? m[0] : '(não achei)'; });
const toasts = (page) => page.evaluate(() => [...document.querySelectorAll('[data-sonner-toast]')].map((e) => e.textContent.trim().slice(0, 120)));
export default async ({ page, shot, t, ms, log, settle, base }) => {
  await page.goto(base + '/configuracoes?tab=usuarios'); await settle(); await ms(900);
  await shot('c09-a-lista');
  log('contador:', await contador(page));
  log('lista:', JSON.stringify((await page.locator('main').innerText()).split('\n').map((l) => l.trim()).filter(Boolean).slice(0, 50)));
  await t('clica Paulo', () => page.locator('main').getByText('Paulo Souza', { exact: true }).first().click());
  await ms(600);
  await shot('c09-b-paulo');
  log('botões do painel:', JSON.stringify(await geom(page, 'main button')).slice(0, 1200));
  await t('Desativar', () => page.locator('main').getByRole('button', { name: 'Desativar', exact: true }).click());
  await page.waitForTimeout(400);
  log('toasts:', JSON.stringify(await toasts(page)));
  await shot('c09-c-desativado');
  await ms(900);
  log('contador após desativar:', await contador(page));
  log('Inativo na lista:', await page.locator('main').getByText('Inativo').count());
  await t('Reativar', () => page.locator('main').getByRole('button', { name: 'Reativar', exact: true }).click());
  await page.waitForTimeout(400);
  log('toasts:', JSON.stringify(await toasts(page)));
  await shot('c09-d-reativado');
  await ms(900);
  log('contador após reativar:', await contador(page));
  await t('Excluir', () => page.locator('main').getByRole('button', { name: 'Excluir', exact: true }).click());
  await ms(600);
  await shot('c09-e-excluir');
  log('diálogo:', JSON.stringify((await page.locator('[role=alertdialog], [role=dialog]').last().innerText()).split('\n').map((l) => l.trim()).filter(Boolean)));
  log('botões do diálogo:', JSON.stringify(await geom(page, '[role=alertdialog] button, [role=dialog] button')));
  await t('Cancelar', () => page.getByRole('button', { name: 'Cancelar', exact: true }).click());
  await ms(500);
  await t('clica Camila', () => page.locator('main').getByText('Camila Duarte', { exact: true }).first().click());
  await ms(600);
  await shot('c09-f-camila');
  log('painel Camila:', JSON.stringify((await page.locator('main').innerText()).split('\n').map((l) => l.trim()).filter(Boolean).slice(40, 80)));
  log('botões do painel Camila:', JSON.stringify((await geom(page, 'main button')).filter((b) => /Editar|Desativar|Excluir/.test(b.t))));
  // cap10: menu da conta
  const cartao = page.locator('aside, nav').getByRole('button').filter({ hasText: 'camila.duarte@' }).first();
  log('cartão da conta rect:', JSON.stringify(await cartao.boundingBox()));
  await t('abre menu da conta', () => cartao.click());
  await ms(700);
  await shot('c10-a-menu');
  log('itens do menu:', JSON.stringify(await page.evaluate(() => [...document.querySelectorAll('[role=menu] [role=menuitem], [role=menu] [role=menuitemradio]')].map((e) => { const r = e.getBoundingClientRect(); return { t: e.textContent.trim().replace(/\s+/g, ' ').slice(0, 40), x: Math.round(r.x), y: Math.round(r.y), w: Math.round(r.width), h: Math.round(r.height) }; }))));
  await t('hover Assinatura', () => page.getByRole('menuitem', { name: 'Assinatura' }).hover());
  await ms(300);
  await shot('c10-b-assinatura');
  await t('Esc', () => page.keyboard.press('Escape'));
  await ms(500);
  log('menu aberto ainda?', await page.locator('[role=menu]').count());
  await shot('c10-c-fechado');
};
